CREATE TABLE users
(
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(20)  NOT NULL DEFAULT 'USER' CHECK (role IN ('USER', 'ADMIN')),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_users_username ON users (lower(username));
CREATE UNIQUE INDEX uq_users_email ON users (lower(email));

CREATE TABLE competitions
(
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    code        VARCHAR(20)  NOT NULL UNIQUE,
    season      VARCHAR(20),
    external_id INTEGER UNIQUE -- id w football-data.org (na później)
);

CREATE TABLE teams
(
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    short_name  VARCHAR(20),
    crest_url   VARCHAR(500),
    external_id INTEGER UNIQUE
);

CREATE TABLE matches
(
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competition_id INTEGER     NOT NULL REFERENCES competitions (id) ON DELETE RESTRICT,
    home_team_id   INTEGER     NOT NULL REFERENCES teams (id) ON DELETE RESTRICT,
    away_team_id   INTEGER     NOT NULL REFERENCES teams (id) ON DELETE RESTRICT,
    kickoff_at     TIMESTAMPTZ NOT NULL,
    stage          VARCHAR(50),
    status         VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED'
        CHECK (status IN ('SCHEDULED', 'FINISHED', 'POSTPONED', 'CANCELLED')),
    home_score     INTEGER CHECK (home_score >= 0),
    away_score     INTEGER CHECK (away_score >= 0),
    external_id    INTEGER UNIQUE,
    CONSTRAINT chk_matches_teams CHECK (home_team_id <> away_team_id)
);
CREATE INDEX idx_matches_competition_kickoff ON matches (competition_id, kickoff_at);

CREATE TABLE leagues
(
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    invite_code VARCHAR(12)  NOT NULL UNIQUE,
    owner_id    INTEGER      NOT NULL REFERENCES users (id),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- które rozgrywki obejmuje liga (np. tylko Liga Mistrzów albo LM + Premier League)
CREATE TABLE league_competitions
(
    league_id      INTEGER NOT NULL REFERENCES leagues (id) ON DELETE CASCADE,
    competition_id INTEGER NOT NULL REFERENCES competitions (id) ON DELETE RESTRICT,
    PRIMARY KEY (league_id, competition_id)
);

CREATE TABLE league_memberships
(
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    league_id INTEGER     NOT NULL REFERENCES leagues (id) ON DELETE CASCADE,
    user_id   INTEGER     NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    role      VARCHAR(20) NOT NULL CHECK (role IN ('OWNER', 'MEMBER')),
    joined_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_membership UNIQUE (league_id, user_id)
);

-- typ jest per liga: w każdej lidze można typować inaczej (można też skopiować typy z innej ligi)
CREATE TABLE predictions
(
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        INTEGER     NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    league_id      INTEGER     NOT NULL REFERENCES leagues (id) ON DELETE CASCADE,
    match_id       INTEGER     NOT NULL REFERENCES matches (id) ON DELETE CASCADE,
    predicted_home INTEGER     NOT NULL CHECK (predicted_home >= 0),
    predicted_away INTEGER     NOT NULL CHECK (predicted_away >= 0),
    points         INTEGER, -- NULL = mecz jeszcze nierozliczony
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_prediction UNIQUE (user_id, league_id, match_id)
);
CREATE INDEX idx_predictions_match ON predictions (match_id);
